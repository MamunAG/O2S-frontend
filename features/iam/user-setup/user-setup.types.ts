export type ApiResponse<T = unknown> = {
  success: boolean
  message: string
  data?: T
}

export type PaginationMeta = {
  total: number
  page: number
  limit: number
  totalPages: number
  hasNextPage: boolean
  hasPreviousPage: boolean
}

export type PaginatedResponse<T> = {
  items: T[]
  meta: PaginationMeta
}

export type UserRole = "admin" | "user"

/** A member of the selected organization: the login and the membership (O2S UserSetupDto). */
export type UserSetupRecord = {
  userId: string
  userName: string
  firstName?: string | null
  lastName?: string | null
  fullName?: string | null
  email?: string | null
  phoneNumber?: string | null
  role: UserRole
  /** The membership: inactive = no access to this organization (the login stays). */
  isActive: boolean
  isAccountActive: boolean
  isGlobalAdmin: boolean
  /** Has a one-time password and has not set their own yet. */
  mustChangePassword: boolean
  temporaryPasswordExpiresAt?: string | null
  /** Belongs to this organization only: its admins may edit the login and issue one-time passwords. */
  isOnlyThisOrganization: boolean
  lastSeenAt?: string | null
  createdDate?: string | null
  createdByName?: string | null
}

/** A created user or a new one-time password: the password is shown once. */
export type OneTimePasswordResult = {
  user: UserSetupRecord
  oneTimePassword: string
  expiresAt: string
  emailed: boolean
}

/** Only UserSetupParams properties: search, isActive, role, mustChangePassword ("" = all). */
export type UserSetupFilterValues = {
  search: string
  isActive: string
  role: string
  mustChangePassword: string
}

export const EMPTY_FILTERS: UserSetupFilterValues = { search: "", isActive: "", role: "", mustChangePassword: "" }

export type UserSetupFormValues = {
  userName: string
  firstName: string
  lastName: string
  email: string
  phoneNumber: string
  role: UserRole
  /** Empty = generated by the server. Create only. */
  oneTimePassword: string
  sendEmail: boolean
}

export const EMPTY_FORM_VALUES: UserSetupFormValues = {
  userName: "",
  firstName: "",
  lastName: "",
  email: "",
  phoneNumber: "",
  role: "user",
  oneTimePassword: "",
  sendEmail: false,
}
